#!/usr/bin/env python3
"""Regenerate STRINGS.md from the JSON translation tables."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "STRINGS.md"


def esc(text: str) -> str:
    return (text.replace("\\", "\\\\")
                .replace("|", "\\|")
                .replace("\r\n", "\u23ce").replace("\n", "\u23ce")
                .replace("\t", "\\t"))


def table(rows, unit: str) -> str:
    lines = [f"| # | Original | English | Budget ({unit}) |",
             "|---:|---|---|---:|"]
    for i, (orig, eng, budget) in enumerate(rows, 1):
        lines.append(f"| {i} | {esc(orig)} | {esc(eng)} | {budget} |")
    return "\n".join(lines)


def main() -> None:
    us = json.loads((DATA / "us.json").read_text(encoding="utf-8"))["strings"]
    bm = json.loads((DATA / "baml.json").read_text(encoding="utf-8"))["strings"]
    js = json.loads((DATA / "js_comments.json").read_text(encoding="utf-8"))["comments"]

    us_rows = [(k, v, len(k.encode("utf-16-le"))) for k, v in us.items()]
    bm_rows = [(k, v, len(k.encode("utf-8"))) for k, v in bm.items()]
    js_rows = [(k, v, len(k)) for k, v in js.items()]

    parts = [
        "# String tables",
        "",
        "Generated by `tools/gen_strings_md.py` from `data/*.json` — do not edit by hand.",
        "",
        f"- Runtime strings (`.NET #US` heap, UTF-16): **{len(us_rows)}**",
        f"- Compiled XAML strings (`BAML` resources, UTF-8): **{len(bm_rows)}**",
        f"- JavaScript comment runs (injected wiki viewer script): **{len(js_rows)}**",
        "",
        "**Budget** is the number of bytes available in the original binary. A translation",
        "must encode to at most that many bytes; the patcher pads the remainder with spaces",
        "so the file size and all internal offsets stay unchanged.",
        "",
        "## Runtime strings (#US heap)",
        "",
        table(us_rows, "UTF-16 bytes"),
        "",
        "## Compiled XAML strings (BAML)",
        "",
        table(bm_rows, "UTF-8 bytes"),
        "",
        "## JavaScript comments (wiki viewer)",
        "",
        "Only CJK runs inside comments are replaced; the code itself is untouched.",
        "",
        table(js_rows, "UTF-16 units"),
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"written {OUT} ({len(us_rows)} / {len(bm_rows)} / {len(js_rows)} rows)")


if __name__ == "__main__":
    main()
